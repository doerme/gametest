'use strict';
const assert = require('assert');
const InputManager = require('../src/input/InputManager');
const events = [];
const handlers = {};
const wx = {};
for (const name of ['TouchStart', 'TouchMove', 'TouchEnd', 'TouchCancel']) {
  wx['on' + name] = (fn) => { handlers[name] = fn; };
  wx['off' + name] = () => { delete handlers[name]; };
}
const input = new InputManager(wx, {});
input.onGesture = (points) => events.push({ type: 'gesture', points });
input.onTap = (point) => events.push({ type: 'tap', point });
input.bind();
const touch = (id, x, y) => ({ identifier: id, clientX: x, clientY: y });
handlers.TouchStart({ touches: [touch(1, 30, 40)] });
handlers.TouchEnd({ changedTouches: [touch(1, 130, 40)] });
assert.strictEqual(events[0].type, 'gesture', 'two samples still form a fast swipe');
handlers.TouchStart({ touches: [touch(1, 30, 40)] });
handlers.TouchMove({ touches: [touch(1, 31, 41)] });
handlers.TouchMove({ touches: [touch(1, 32, 42)] });
handlers.TouchEnd({ changedTouches: [touch(1, 31, 41)] });
assert.strictEqual(events[1].type, 'tap', 'many jitter samples remain a tap');
handlers.TouchStart({ touches: [touch(7, 10, 20)] });
handlers.TouchStart({ touches: [touch(7, 10, 20), touch(9, 300, 300)] });
handlers.TouchEnd({ touches: [touch(7, 10, 20)], changedTouches: [touch(9, 300, 300)] });
assert.strictEqual(input.activeId, 7);
handlers.TouchMove({ touches: [touch(9, 300, 300), touch(7, 100, 20)] });
handlers.TouchEnd({ changedTouches: [touch(7, 150, 20)] });
assert.deepStrictEqual(events[2].points.map((p) => [p.x, p.y]), [[10, 20], [100, 20], [150, 20]]);
handlers.TouchStart({ touches: [touch(1, 20, 20)] });
handlers.TouchMove({ touches: [touch(1, 100, 20)] });
handlers.TouchCancel({ changedTouches: [] });
assert.strictEqual(input.isDrawing, false);
assert.strictEqual(events.length, 3, 'cancel never casts or taps');
input.destroy(); assert.deepStrictEqual(handlers, {});

const pointerHandlers = {};
const canvas = { width: 1500, height: 2500, getBoundingClientRect: () => ({ left: 50, top: 100, width: 300, height: 500 }), addEventListener: (name, fn) => { pointerHandlers[name] = fn; }, removeEventListener: (name) => { delete pointerHandlers[name]; }, setPointerCapture() {} };
const pointer = new InputManager(null, canvas, { getSize: () => ({ width: 375, height: 625 }), isUiPoint: (p) => p.y < 40 });
pointer.onGesture = (points) => events.push({ type: 'pointer', points }); pointer.onTap = (point) => events.push({ type: 'ui', point }); pointer.bind();
const event = (x, y, id = 2) => ({ pointerId: id, clientX: x, clientY: y, button: 0 });
pointerHandlers.pointerdown(event(70, 200)); pointerHandlers.pointerup(event(230, 200));
assert.deepStrictEqual(events[3].points.map((p) => [p.x, p.y]), [[25, 125], [225, 125]], 'CSS coordinates ignore backing store DPR');
pointerHandlers.pointerdown(event(70, 110)); pointerHandlers.pointerup(event(70, 112));
assert.strictEqual(events[4].type, 'ui');
pointerHandlers.pointerdown(event(70, 110)); pointerHandlers.pointermove(event(230, 180)); pointerHandlers.pointerup(event(230, 180));
assert.strictEqual(events.length, 5, 'dragging from a UI control never casts');
pointerHandlers.pointerdown(event(70, 200)); pointerHandlers.pointercancel(event(230, 200)); assert.strictEqual(events.length, 5);
pointer.destroy(); assert.deepStrictEqual(pointerHandlers, {});
console.log('input-manager.test.js passed');
