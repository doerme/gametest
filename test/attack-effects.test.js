'use strict';
const assert = require('assert');
const THREE = require('three');
const { GameState } = require('../src/core/GameState');
const Enemy = require('../src/entities/Enemy');
const AttackEffects = require('../src/three/AttackEffects');
const ATTACK = require('../src/core/AttackEffect');
const right = [{ x: 30, y: 300 }, { x: 140, y: 300 }];
const up = [{ x: 50, y: 300 }, { x: 50, y: 190 }];
const makeEnemy = (symbols = ['right', 'up']) => new Enemy({ x: 90, y: 180, symbols, speed: 1 });
const run = () => { const state = new GameState(390, 844); state.start('normal', 'symbol'); state.director.index = state.director.total; return state; };
let state = run();
const survivor = makeEnemy(), killed = makeEnemy(['right']), other = makeEnemy(['left']);
state.enemies = [survivor, killed, other];
state.handleGesture(right);
assert.strictEqual(state.score, 130, 'score is applied before projectile arrival');
assert.strictEqual(state.combo, 1);
assert.deepStrictEqual(survivor.symbols, ['up']);
assert.strictEqual(survivor.dead, false);
let attacks = state.effects.filter((e) => e.type === 'attack');
assert.strictEqual(attacks.length, 1, 'only surviving matched enemies receive a projectile');
assert.strictEqual(attacks[0].target, survivor);
assert.strictEqual(attacks[0].duration, ATTACK.flightDuration + ATTACK.impactDuration);
assert.ok(state.effects.some((e) => e.type === 'vanish') && state.effects.some((e) => e.type === 'lightning'));
state.handleGesture(up);
assert.strictEqual(state.effects.filter((e) => e.type === 'attack').length, 0, 'a later fatal gesture cancels the in-flight shot');
state = run(); state.enemies = [makeEnemy(['right', 'right', 'up'])];
state.handleGesture(right); state.handleGesture(right);
assert.strictEqual(state.score, 60); assert.strictEqual(state.combo, 2);
assert.strictEqual(state.effects.filter((e) => e.type === 'attack').length, 2, 'rapid correct gestures can each launch a shot at the same living target');
state.handleGesture(up); assert.ok(!state.effects.some((e) => e.type === 'attack'));
for (const points of [[{ x: 3, y: 3 }, { x: 3, y: 3 }], right]) {
  const empty = run(); empty.handleGesture(points); assert.ok(!empty.effects.some((e) => e.type === 'attack'));
  const miss = run(); miss.enemies = [makeEnemy(['left', 'up'])]; miss.handleGesture(points); assert.ok(!miss.effects.some((e) => e.type === 'attack'));
}
state = run(); state.enemies = [makeEnemy(), makeEnemy()]; state.handleGesture(right);
assert.strictEqual(state.effects.filter((e) => e.type === 'attack').length, 2, 'one projectile per surviving target');
state.updateAnimations(0.399); assert.strictEqual(state.effects.filter((e) => e.type === 'attack').length, 2);
state.updateAnimations(0.002); assert.ok(!state.effects.some((e) => e.type === 'attack'), 'effects expire on real animation time');
for (const action of ['resize', 'transition', 'restart', 'contact', 'comboItem']) {
  const s = run(), enemy = makeEnemy(); s.enemies = [enemy]; s.handleGesture(right);
  if (action === 'resize') s.resize(320, 568);
  if (action === 'transition') s.beginLevelTransition();
  if (action === 'restart') s.start('normal', 'symbol');
  if (action === 'contact') { enemy.x = s.hero.x; enemy.y = s.hero.y; s.update(0.016); assert.strictEqual(s.lives, 4); }
  if (action === 'comboItem') s.triggerComboChain([enemy]);
  assert.ok(!s.effects.some((e) => e.type === 'attack'), action + ' cancels projectiles');
}
state = run(); state.enemies = [makeEnemy()];
for (let i = 0; i < 30; i++) state.triggerAttack(state.enemies[0]);
assert.strictEqual(state.effects.filter((e) => e.type === 'attack').length, ATTACK.maxActive);

const scene = new THREE.Scene(), camera = new THREE.PerspectiveCamera(); camera.position.set(0, 6, 10); camera.lookAt(0, 0, 0);
const origin = new THREE.Vector3(0, 1, 4), target = new THREE.Vector3(0, 1, -4);
let resolvable = true;
const effects = new AttackEffects(scene, () => origin.clone(), () => resolvable ? target.clone() : null, camera);
const enemy = { dead: false, reachedHero: false };
const shot = () => ({ type: 'attack', target: enemy, radius: 38, age: 0, duration: 0.4 });
let event = shot(); effects.update([event]);
const slot = effects.active.get(event);
assert.ok(slot.position.distanceTo(origin) < 1e-7, 'projectile begins exactly at castTip');
event.age = 0.09; effects.update([event]);
assert.ok(slot.position.distanceTo(origin) > 1, 'projectile advances in flight');
const previous = slot.position.clone(); target.x = 1; effects.update([event]);
assert.ok(slot.position.x > previous.x, 'flight tracks the moving endpoint');
const fixedStart = slot.origin.clone(); origin.x = 3; effects.update([event]);
assert.ok(slot.origin.distanceTo(fixedStart) < 1e-7, 'existing projectiles do not jump with a later staff animation');
event.age = ATTACK.flightDuration; effects.update([event]);
assert.strictEqual(slot.phase, 'impact'); assert.ok(slot.position.distanceTo(target) < 1e-7, 'impact is centered on the target');
assert.ok(effects.colors.array.some((value, index) => index % 4 === 3 && value > 0), 'the visible batch includes alpha');
const drawCount = effects.geometry.drawRange.count;
assert.ok(Array.from(effects.positions.array.slice(0, drawCount * 3)).every(Number.isFinite));
enemy.dead = true; effects.update([event]); assert.strictEqual(effects.active.size, 0); assert.strictEqual(effects.mesh.visible, false);
enemy.dead = false;
event = shot(); effects.update([event]); resolvable = false; effects.update([event]);
assert.strictEqual(effects.active.size, 0, 'removed render targets cancel safely');
resolvable = true; effects.update([event]); assert.strictEqual(effects.active.size, 0, 'a cancelled shot cannot replay');
const many = Array.from({ length: 30 }, shot); effects.update(many); assert.strictEqual(effects.active.size, 24);
assert.ok(effects.geometry.drawRange.count <= effects.positions.count, 'maximum batch fits its buffers');
assert.ok(effects.geometry.drawRange.count / 3 <= 4200, 'attack batch stays low-poly');
const count = effects.slots.length;
effects.update([]); effects.update(many); assert.strictEqual(effects.slots.length, count, 'shots reuse their pool slots');
effects.clear(); assert.strictEqual(effects.active.size, 0); effects.update(many); assert.strictEqual(effects.mesh.visible, false, 'cleared effects cannot reappear after a resize');
let disposed = 0;
for (const resource of [effects.geometry, effects.material, effects.orb]) resource.addEventListener('dispose', () => disposed++);
effects.dispose(); assert.strictEqual(disposed, 3); assert.strictEqual(scene.children.length, 0);
console.log('attack-effects.test.js passed');
